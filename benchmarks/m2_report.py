"""Compile the 3D-vs-axisymmetric cross-validation records into docs/validation/m2_3d_vs_2d.md.

    python benchmarks/m2_report.py

Reads benchmarks/records/m2_cross_*_p2*.json (written by benchmarks/m2_cross.py).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REC = ROOT / "benchmarks" / "records"
OUT = ROOT / "docs" / "validation" / "m2_3d_vs_2d.md"
KEYS = [("Psi_SI_H_T_m2", "Ψ"), ("L_p_H", "L_p"), ("W_mag_J", "W"), ("g_factor", "g")]


def rows(pattern: str):
    out = []
    for p in sorted(REC.glob(pattern)):
        j = json.loads(p.read_text())
        m = re.search(r"_h([0-9.]+)", j["case"])
        h = float(m.group(1)) if m else float("nan")
        out.append((h, j, p.name))
    return sorted(out, key=lambda t: -t[0])


def table(title: str, pattern: str) -> str:
    rs = rows(pattern)
    if not rs:
        return f"### {title}\n\n(no records yet)\n"
    lines = [f"### {title}", "",
             "| h [m] | DOFs | boundary | " + " | ".join(f"{n} rel. diff." for _, n in KEYS) +
             " | 3D solver | 3D time [s] | record |",
             "|---|---|---|" + "---|" * len(KEYS) + "---|---|---|"]
    for h, j, name in rs:
        vals = " | ".join(f"{j[k]['rel_diff']:+.2e}" for k, _ in KEYS)
        res = (j.get("solver_3d") or {}).get("max_relative_residual")
        ok = res is None or res < 1e-6
        status = "converged" if ok else f"**not converged** (residual {res:.1e})"
        if not ok:
            vals = " | ".join(f"({j[k]['rel_diff']:+.2e})" for k, _ in KEYS)
        lines.append(f"| {h:g} | {j['dofs_3d']:,} | {j.get('open_boundary', 'truncated (n x A = 0)')} | {vals} | "
                     f"{status} | {j['seconds_3d']:.0f} | `{name}` |")
    return "\n".join(lines) + "\n"


def main():
    parts = [
        "# 3D engine vs axisymmetric engine",
        "",
        "Generated by `benchmarks/m2_report.py` from the records of `benchmarks/m2_cross.py` (ND2 elements in 3D;",
        "the axisymmetric reference is converged to well below the differences shown). Relative difference",
        "= (3D - 2D)/2D.",
        "",
        table("Solenoid + coax (template, R = 1, H = 2), infinity shell", "m2_cross_solenoid_h*_p2.json"),
        table("Solenoid + coax, earlier truncated boundary (n x A = 0 at 2.5x the device)", "m2_cross_solenoid_h*_p2_dirichlet.json"),
        table("Toroid, closed sheath carrying the readout current (3D pickup 'azimuthal' = the 2D ideal slit)",
              "m2_cross_toroid_ideal_h*_p2.json"),
        table("Toroid, real slit 6° fed by a port", "m2_cross_toroid_slit6_h*_p2.json"),
        table("Toroid, real slit 3° fed by a port", "m2_cross_toroid_slit3_h*_p2.json"),
        table("Toroid, real slit 1.5° fed by a port", "m2_cross_toroid_slit1.5_h*_p2.json"),
        "## Reading",
        "",
        "- Solenoid: with the infinity shell the 3D results converge to the axisymmetric ones (|Δ| ≤ 1e-5 at",
        "  h = 0.2). The truncated boundary biased Ψ and W by -0.44 % independently of the mesh.",
        "- Toroid with the native azimuthal pickup (closed sheath carrying the readout current, exactly the",
        "  axisymmetric ideal slit): Ψ, L_p and W converge to the axisymmetric values at about O(h²).",
        "- Toroid with a real slit fed by a port: Ψ and L_p stay 1–3 % above the ideal slit and the excess does not",
        "  vanish under refinement. The port feeds the readout current with a uniform-conductivity distribution,",
        "  which has to redistribute into the Meissner surface current over the size of the sheath cross-section.",
        "  This is a property of the slit/port model, not a solver error; use it only to",
        "  study a real slit and its feed. Narrow slits (1.5°) make AMS-PCG stall at ND2; values in parentheses",
        "  come from solves that did not converge and are not reliable.",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
