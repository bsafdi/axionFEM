std::vector<uint32_t> checked_indices(const Arr& a, size_t nverts, const std::string& where) {
  for (uint32_t k : a.u)
    AXF_REQUIRE(k < nverts, strcat("triangle index ", k, " is out of range (", nverts, " vertices)"), where,
                "the scene's index array does not match its vertex array; export the scene again");
  return a.u;
}

Scene load_scene(const json& s) {
  AXF_REQUIRE(s.is_object(), "scene must be a JSON object", "/", "pass the output of Model.scene() / axf solve --scene");
  if (s.contains("schema"))
    AXF_REQUIRE(s["schema"].is_string() && s["schema"].get<std::string>().rfind("axionfem.scene/", 0) == 0,
                "unsupported scene schema", "/schema", "expected \"axionfem.scene/1\"");
  Scene S;
  if (s.contains("name") && s["name"].is_string()) S.name = s["name"].get<std::string>();
  if (s.contains("symmetry") && s["symmetry"].is_string() && s["symmetry"].get<std::string>() == "3d") {
    S.dim3 = true;
    AXF_REQUIRE(s.contains("regions") && s["regions"].is_array(), "3D scene has no regions", "/regions");
    for (size_t k = 0; k < s["regions"].size(); ++k) {
      const json& r = s["regions"][k];
      const std::string w = "/regions/" + std::to_string(k);
      Region R;
      R.name = r.value("name", "region" + std::to_string(k));
      R.role = r.value("role", "vacuum");
      R.material = r.value("material", "");
      R.color = hexcolor(r.contains("color") ? r["color"] : json(), role_color(R.role));
      std::vector<float> V;
      std::vector<uint32_t> I;
      if (r.contains("surface")) {
        const Arr Va = typed(r["surface"].at("vertices"), w + "/surface/vertices", "float32", 3);
        const Arr Ia = typed(r["surface"].at("indices"), w + "/surface/indices", "uint32", 3);
        V = Va.f;
        I = checked_indices(Ia, static_cast<size_t>(Va.rows), w + "/surface/indices");
      }
      S.regions.push_back(std::move(R));
      S.SV.push_back(std::move(V));
      S.SI.push_back(std::move(I));
    }
    if (s.contains("slices") && s["slices"].is_array()) {
      std::map<std::string, C3> col_of;
      for (const Region& R : S.regions) col_of[R.name] = R.color;
      for (size_t k = 0; k < s["slices"].size(); ++k) {
        const json& f = s["slices"][k];
        const std::string w = "/slices/" + std::to_string(k);
        const Arr V = typed(f.at("vertices"), w + "/vertices", "float32", 3);
        const Arr I = typed(f.at("indices"), w + "/indices", "uint32", 3);
        const uint32_t base = static_cast<uint32_t>(S.FV.size() / 3);
        S.FV.insert(S.FV.end(), V.f.begin(), V.f.end());
        for (uint32_t id : checked_indices(I, static_cast<size_t>(V.rows), w + "/indices")) S.FI.push_back(base + id);
        std::vector<uint32_t> ra;
        if (f.contains("region_attr")) ra = typed(f["region_attr"], w + "/region_attr", "uint32", 1).u;
        for (size_t t = 0; t < I.u.size() / 3; ++t) {
          C3 c = role_color("superconductor");
          if (t < ra.size() && s.contains("attr_names")) {
            const std::string an = s["attr_names"].value(std::to_string(ra[t]), std::string());
            if (col_of.count(an)) c = col_of[an];
          }
          S.FIcol.push_back(c);
        }
        S.has_field = true;
        if (k == 0 && f.contains("quantities") && f["quantities"].is_object())
          for (auto it = f["quantities"].begin(); it != f["quantities"].end(); ++it) S.quantities.push_back(it.key());
      }
    }
    if (s.contains("cutaway") && s["cutaway"].contains("center")) {
      S.cut_x = s["cutaway"]["center"].at(0).get<double>();
      S.cut_y = s["cutaway"]["center"].at(1).get<double>();
    }
    if (s.contains("summary") && s["summary"].is_object()) S.summary = s["summary"];
    double b[6] = {kInf, kInf, kInf, -kInf, -kInf, -kInf};
    for (const auto& V : S.SV)
      for (size_t i = 0; i + 2 < V.size(); i += 3)
        for (int k = 0; k < 3; ++k) b[k] = std::min<double>(b[k], V[i + k]), b[3 + k] = std::max<double>(b[3 + k], V[i + k]);
    if (s.contains("extent3")) {
      for (int k = 0; k < 3; ++k) {
        b[k] = s["extent3"].at("min").at(k).get<double>();
        b[3 + k] = s["extent3"].at("max").at(k).get<double>();
      }
    }
    AXF_REQUIRE(b[5] > b[2], "the 3D scene has no geometry", "/regions");
    for (int k = 0; k < 6; ++k) S.ext3[k] = b[k];
    S.ext_r = std::max({std::fabs(b[0]), std::fabs(b[1]), std::fabs(b[3]), std::fabs(b[4])});
    S.ext_z0 = b[2];
    S.ext_z1 = b[5];
    S.view_r = S.ext_r;
    S.view_z0 = b[2];
    S.view_z1 = b[5];
    return S;
  }
  // regions
  if (s.contains("regions")) {
    AXF_REQUIRE(s["regions"].is_array(), "regions must be a list", "/regions");
    for (size_t k = 0; k < s["regions"].size(); ++k) {
      const json& r = s["regions"][k];
      const std::string w = "/regions/" + std::to_string(k);
      Region R;
      R.name = r.value("name", "region" + std::to_string(k));
      R.role = r.value("role", "vacuum");
      R.material = r.value("material", "");
      R.color = hexcolor(r.contains("color") ? r["color"] : json(), role_color(R.role));
      if (r.contains("triangles")) {
        const Arr V = typed(r["triangles"].at("vertices"), w + "/triangles/vertices", "float32", 2);
        const Arr I = typed(r["triangles"].at("indices"), w + "/triangles/indices", "uint32", 3);
        R.V = V.f;
        R.I = checked_indices(I, static_cast<size_t>(V.rows), w + "/triangles/indices");
      }
      if (r.contains("outline")) {
        AXF_REQUIRE(r["outline"].is_array(), "outline must be a list of polylines", w + "/outline");
        for (size_t l = 0; l < r["outline"].size(); ++l) {
          const Arr L = typed(r["outline"][l], w + "/outline/" + std::to_string(l), "float32", 2);
          std::vector<P2> loop(static_cast<size_t>(L.rows));
          for (size_t i = 0; i < loop.size(); ++i) loop[i] = {L.f[2 * i], L.f[2 * i + 1]};
          // outlines are closed loops; make the closure explicit
          if (loop.size() > 2 && (loop.front().x != loop.back().x || loop.front().y != loop.back().y))
            loop.push_back(loop.front());
          R.loops.push_back(std::move(loop));
        }
      }
      S.regions.push_back(std::move(R));
    }
  }
  if (s.contains("curves") && s["curves"].is_array())
    for (size_t k = 0; k < s["curves"].size(); ++k)
      if (s["curves"][k].contains("segments")) {
        S.curves.push_back(
            typed(s["curves"][k]["segments"], "/curves/" + std::to_string(k) + "/segments", "float32", 2).f);
        S.curve_roles.push_back(s["curves"][k].value("role", std::string("superconductor")));
      }
  // field
  if (s.contains("field") && s["field"].is_object()) {
    const json& f = s["field"];
    const Arr V = typed(f.at("vertices"), "/field/vertices", "float32", 2);
    const Arr I = typed(f.at("indices"), "/field/indices", "uint32", 3);
    S.FV = V.f;
    S.FI = checked_indices(I, static_cast<size_t>(V.rows), "/field/indices");
    S.has_field = true;
    if (f.contains("quantities") && f["quantities"].is_object())
      for (auto it = f["quantities"].begin(); it != f["quantities"].end(); ++it) S.quantities.push_back(it.key());
  }
  if (s.contains("field_lines") && s["field_lines"].is_object()) {
    const json& fl = s["field_lines"];
    if (fl.contains("static")) S.lines_static = typed(fl["static"], "/field_lines/static", "float32", 2).f;
    if (fl.contains("static_label") && fl["static_label"].is_string()) S.lines_static_label = fl["static_label"].get<std::string>();
    if (fl.contains("pickup")) S.lines_pickup = typed(fl["pickup"], "/field_lines/pickup", "float32", 2).f;
  }
  if (s.contains("summary") && s["summary"].is_object()) S.summary = s["summary"];
  // extent: given, or the bounding box of the regions
  double rmax = 0, z0 = kInf, z1 = -kInf;
  for (const Region& R : S.regions) {
    for (size_t i = 0; i + 1 < R.V.size(); i += 2) {
      rmax = std::max<double>(rmax, R.V[i]);
      z0 = std::min<double>(z0, R.V[i + 1]);
      z1 = std::max<double>(z1, R.V[i + 1]);
    }
    for (const auto& L : R.loops)
      for (const P2& p : L) rmax = std::max(rmax, p.x), z0 = std::min(z0, p.y), z1 = std::max(z1, p.y);
  }
  for (const auto& c : S.curves)
    for (size_t i = 0; i + 1 < c.size(); i += 2)
      rmax = std::max<double>(rmax, c[i]), z0 = std::min<double>(z0, c[i + 1]), z1 = std::max<double>(z1, c[i + 1]);
  if (s.contains("extent") && s["extent"].is_object()) {
    const json& e = s["extent"];
    rmax = e.value("r_max", rmax);
    z0 = e.value("z_min", z0);
    z1 = e.value("z_max", z1);
  }
  if (!(z1 > z0) && S.has_field) {  // nothing but a field: use its bounding box
    for (size_t i = 0; i + 1 < S.FV.size(); i += 2)
      rmax = std::max<double>(rmax, S.FV[i]), z0 = std::min<double>(z0, S.FV[i + 1]),
      z1 = std::max<double>(z1, S.FV[i + 1]);
  }
  AXF_REQUIRE(z1 > z0 && rmax > 0 && std::isfinite(rmax),
              "the scene has no geometry to draw (no regions, curves or field)", "/regions",
              "export the scene from a meshed or solved model");
  S.ext_r = rmax;
  S.ext_z0 = z0;
  S.ext_z1 = z1;
  const double zc = 0.5 * (z0 + z1), half = 1.3 * std::max(rmax, 0.5 * (z1 - z0));
  S.view_r = half;
  S.view_z0 = zc - half;
  S.view_z1 = zc + half;
  if (s.contains("view") && s["view"].is_object()) {
    const json& v = s["view"];
    S.view_r = v.value("r_max", S.view_r);
    S.view_z0 = v.value("z_min", S.view_z0);
    S.view_z1 = v.value("z_max", S.view_z1);
    AXF_REQUIRE(S.view_r > 0 && S.view_z1 > S.view_z0, "scene view window is empty", "/view",
                "r_max must be > 0 and z_max > z_min");
  }
  return S;
}

