std::vector<uint8_t> b64decode(const std::string& s, const std::string& where) {
  static const std::array<int8_t, 256> T = [] {
    std::array<int8_t, 256> a{};
    a.fill(-1);
    const char* c = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    for (int i = 0; i < 64; ++i) a[static_cast<unsigned char>(c[i])] = static_cast<int8_t>(i);
    return a;
  }();
  std::vector<uint8_t> out;
  out.reserve(s.size() / 4 * 3 + 3);
  uint32_t acc = 0;
  int nb = 0;
  for (char ch : s) {
    if (ch == '=') break;
    if (ch == '\n' || ch == '\r' || ch == ' ') continue;
    const int v = T[static_cast<unsigned char>(ch)];
    AXF_REQUIRE(v >= 0, "invalid base64 character in a typed array", where,
                "typed arrays are standard base64 of little-endian binary (docs/scene_format.md)");
    acc = (acc << 6) | static_cast<uint32_t>(v);
    nb += 6;
    if (nb >= 8) {
      nb -= 8;
      out.push_back(static_cast<uint8_t>((acc >> nb) & 0xFFu));
    }
  }
  return out;
}

struct Arr {
  long rows = 0, cols = 0;
  std::vector<float> f;
  std::vector<uint32_t> u;
};

Arr typed(const json& j, const std::string& where, const std::string& dtype, long cols_want) {
  AXF_REQUIRE(j.is_object() && j.contains("dtype") && j.contains("shape") && j.contains("data"),
              "expected a typed array {\"dtype\", \"shape\", \"data\"}", where, "see docs/scene_format.md");
  const std::string dt = j["dtype"].get<std::string>();
  AXF_REQUIRE(dt == dtype, "typed array has dtype '" + dt + "', expected '" + dtype + "'", where,
              "see docs/scene_format.md");
  const json& sh = j["shape"];
  AXF_REQUIRE(sh.is_array() && !sh.empty() && sh.size() <= 2 && sh[0].is_number_integer(),
              "typed array shape must be [rows] or [rows, cols]", where);
  Arr a;
  a.rows = sh[0].get<long>();
  a.cols = sh.size() == 2 ? sh[1].get<long>() : 1;
  AXF_REQUIRE(a.rows >= 0 && a.cols >= 1, "typed array shape is negative or zero", where);
  if (cols_want > 0)
    AXF_REQUIRE(a.cols == cols_want, strcat("typed array has ", a.cols, " columns, expected ", cols_want), where);
  const std::vector<uint8_t> b = b64decode(j["data"].get<std::string>(), where);
  const size_t n = static_cast<size_t>(a.rows) * static_cast<size_t>(a.cols);
  AXF_REQUIRE(b.size() == 4 * n, strcat("typed array data has ", b.size(), " bytes but shape [", a.rows, ", ",
                                        a.cols, "] needs ", 4 * n),
              where, "the scene file is truncated or was edited by hand; export it again");
  auto word = [&](size_t i) {
    return static_cast<uint32_t>(b[4 * i]) | (static_cast<uint32_t>(b[4 * i + 1]) << 8) |
           (static_cast<uint32_t>(b[4 * i + 2]) << 16) | (static_cast<uint32_t>(b[4 * i + 3]) << 24);
  };
  if (dt == "float32") {
    a.f.resize(n);
    for (size_t i = 0; i < n; ++i) {
      const uint32_t w = word(i);
      std::memcpy(&a.f[i], &w, 4);
    }
  } else {
    a.u.resize(n);
    for (size_t i = 0; i < n; ++i) a.u[i] = word(i);
  }
  return a;
}

