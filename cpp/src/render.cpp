  struct PanelGeom {
    double w = 0, h = 0, label_w = 0, pad = 0, lh = 0;
    int sc = 2;
  };

  PanelGeom panel_geom(const std::vector<Row>& R, int scale) const {
    PanelGeom g;
    g.sc = scale;
    g.pad = std::round(12 * u);
    g.lh = 11 * scale + std::round(1 * u);
    double kvw = 0, other = 0;
    for (const Row& r : R)
      if (r.kind == Row::KV) g.label_w = std::max(g.label_w, text_width(r.a, scale));
    g.label_w += 2 * 6 * scale;
    const double sw = 9 * scale;  // swatch / line key width
    for (const Row& r : R) {
      switch (r.kind) {
        case Row::Header: other = std::max(other, text_width(r.a, scale) + scale); break;
        case Row::Note: other = std::max(other, text_width(r.a, scale)); break;
        case Row::KV: kvw = std::max(kvw, g.label_w + text_width(r.b, scale)); break;
        case Row::Swatch:
          other = std::max(other, sw + 6 * scale + text_width(r.a, scale) + 2 * 6 * scale + text_width(r.b, scale));
          break;
        case Row::LineKey: other = std::max(other, 3 * sw + 6 * scale + text_width(r.a, scale)); break;
      }
      g.h += g.lh + r.gap_before * g.lh;
    }
    g.w = std::max(kvw, other) + 2 * g.pad;
    g.h += 2 * g.pad - std::round(1 * u);
    return g;
  }

  void draw_panel(const std::vector<Row>& R, const PanelGeom& g, double x, double y, double max_h) {
    cv.rect(x, y, x + g.w, y + std::min(g.h, max_h), th.panel);
    cv.frame({x, y, x + g.w, y + std::min(g.h, max_h)}, std::max(1.0, std::round(u)), th.border);
    const int k = g.sc;
    double cy = y + g.pad;
    const double sw = 9 * k;
    for (const Row& r : R) {
      cy += r.gap_before * g.lh;
      if (cy + g.lh > y + max_h - g.pad + 1) break;  // out of room
      const double tx = x + g.pad;
      switch (r.kind) {
        case Row::Header: draw_text(cv, tx, cy, r.a, k, th.accent, true); break;
        case Row::Note: draw_text(cv, tx, cy, r.a, k, th.muted); break;
        case Row::KV:
          draw_text(cv, tx, cy, r.a, k, th.muted);
          draw_text(cv, tx + g.label_w, cy, r.b, k, th.fg);
          break;
        case Row::Swatch: {
          const double sy = cy + 0 * k;
          cv.rect(tx, sy, tx + sw, sy + 7 * k, r.col);
          cv.frame({tx, sy, tx + sw, sy + 7 * k}, std::max(1.0, std::round(u)), th.outline);
          draw_text(cv, tx + sw + 6 * k, cy, r.a, k, th.fg);
          draw_text(cv, tx + sw + 6 * k + text_width(r.a, k) + 2 * 6 * k, cy, r.b, k, th.muted);
          break;
        }
        case Row::LineKey: {
          // the line drawn on a chip of the colour map's dark end, as in the plot
          const C3 chip = !q.empty() ? cm.at(cm.diverging ? 0.5 : 0.12) : th.nodata;
          cv.rect(tx, cy - 1 * k, tx + 3 * sw, cy + 8 * k, chip);
          const IBox clip = cv.full();
          const LineStyle& L = (r.a.find("pickup") != std::string::npos) ? ls_pickup : ls_static;
          seg(clip, {tx + 2 * k, cy + 3.5 * k}, {tx + 3 * sw - 2 * k, cy + 3.5 * k}, 1.4 * u);
          flush(L.col, 1.f);
          draw_text(cv, tx + 3 * sw + 6 * k, cy, r.a, k, th.fg);
          break;
        }
      }
      cy += g.lh;
    }
  }

  // Common layout: title, colour bar column and panel at the right.  Returns
  // the box left for the plot (including its axis labels).
  struct Furniture {
    std::vector<Row> rows;
    PanelGeom pg;
    double panel_x = 0;
    CbarLabels cl;
    double cbar_w = 0;
  };

  Furniture plan_furniture(const json& scene) {
    Furniture F;
    const double m = std::round(14 * u);
    const double top = content_top();
    if (o.annotate) {
      F.rows = panel_rows();
      int k = s;
      F.pg = panel_geom(F.rows, k);
      while (k > 1 && (F.pg.w > 0.42 * W || F.pg.h > H - top - m)) F.pg = panel_geom(F.rows, --k);
      F.panel_x = W - m - F.pg.w;
    } else {
      F.panel_x = W - m;
    }
    if (!q.empty()) {
      F.cl = cbar_labels(scene);
      F.cbar_w = cbar_width(F.cl);
    }
    return F;
  }

  // ---------------------------------------------------------------- section view
  void section(const json& scene) {
    Furniture F = plan_furniture(scene);
    const double m = std::round(14 * u);
    const double top = content_top();
    const double xmin = -sc.view_r, xmax = sc.view_r, zmin = sc.view_z0, zmax = sc.view_z1;
    // ticks: one step for both axes (equal aspect)
    double step_x, step_z;
    nice_ticks(xmin, xmax, 7, step_x);
    nice_ticks(zmin, zmax, 7, step_z);
    const double step = std::max(step_x, step_z);
    std::vector<double> xt, zt;
    for (long k = static_cast<long>(std::ceil(xmin / step - 1e-9)); k <= static_cast<long>(std::floor(xmax / step + 1e-9)); ++k)
      xt.push_back(k * step);
    for (long k = static_cast<long>(std::ceil(zmin / step - 1e-9)); k <= static_cast<long>(std::floor(zmax / step + 1e-9)); ++k)
      zt.push_back(k * step);
    double zlab_w = 0;
    for (double z : zt) zlab_w = std::max(zlab_w, text_width(tick_label(z, step), s));
    const double gap_t = std::round(7 * u);
    const double left = m + 9 * s + std::round(10 * u) + zlab_w + gap_t;
    const double bottom = H - m - (gap_t + 7 * s + std::round(10 * u) + 9 * s);
    const double cbar_gap = q.empty() ? 0 : std::round(26 * u);
    const double right = F.panel_x - std::round(28 * u) - F.cbar_w - cbar_gap;
    AXF_REQUIRE(right - left > 50 && bottom - top > 50,
                strcat("image ", W, "x", H, " is too small for the section view"), "/render",
                "use at least 640x400, or set annotate=false");
    const double k = std::min((right - left) / (xmax - xmin), (bottom - top) / (zmax - zmin));
    const double pw = k * (xmax - xmin), ph = k * (zmax - zmin);
    const double extra = (right - left) - pw;
    const double x0 = std::round(left + 0.5 * extra), y0 = std::round(top + 0.5 * ((bottom - top) - ph));
    const Box plot{x0, y0, x0 + pw, y0 + ph};
    auto X = [&](double x) { return plot.x0 + (x - xmin) * k; };
    auto Y = [&](double z) { return plot.y0 + (zmax - z) * k; };
    out.plot_x0 = static_cast<int>(std::lround(plot.x0));
    out.plot_y0 = static_cast<int>(std::lround(plot.y0));
    out.plot_x1 = static_cast<int>(std::lround(plot.x1));
    out.plot_y1 = static_cast<int>(std::lround(plot.y1));
    out.x_min = xmin, out.x_max = xmax, out.z_min = zmin, out.z_max = zmax;

    const IBox clip = cv.ibox(plot);
    cv.rect(plot.x0, plot.y0, plot.x1, plot.y1, th.nodata);

    // material fills (hatched), under the field
    const double hatch = std::max(4.0, std::round(7 * u));
    for (const Region& g : sc.regions) {
      if (g.role == "vacuum" && !q.empty()) continue;
      const C3 base = g.color, dark = mix(g.color, {0, 0, 0}, 0.28f);
      for (int mir : {1, -1})
        for (size_t t = 0; t + 2 < g.I.size(); t += 3) {
          const uint32_t a = g.I[t], b = g.I[t + 1], c = g.I[t + 2];
          raster_tri(clip, X(mir * g.V[2 * a]) * ss, Y(g.V[2 * a + 1]) * ss, X(mir * g.V[2 * b]) * ss,
                     Y(g.V[2 * b + 1]) * ss, X(mir * g.V[2 * c]) * ss, Y(g.V[2 * c + 1]) * ss,
                     [&](int x, int y, double, double, double) {
                       const double h = std::fmod((x + y + 1.0) / ss, hatch);
                       cv.put(x, y, h < 1.1 * u ? dark : base);
                     });
        }
    }
    // field map
    if (!q.empty()) {
      const std::vector<float>& V = sc.FV;
      for (int mir : {1, -1})
        for (size_t t = 0; t + 2 < sc.FI.size(); t += 3) {
          const uint32_t a = sc.FI[t], b = sc.FI[t + 1], c = sc.FI[t + 2];
          const double va = qv[a], vb = qv[b], vc = qv[c];
          if (!(std::isfinite(va) && std::isfinite(vb) && std::isfinite(vc))) continue;
          raster_tri(clip, X(mir * V[2 * a]) * ss, Y(V[2 * a + 1]) * ss, X(mir * V[2 * b]) * ss, Y(V[2 * b + 1]) * ss,
                     X(mir * V[2 * c]) * ss, Y(V[2 * c + 1]) * ss, [&](int x, int y, double w0, double w1, double w2) {
                       const double v = w0 * va + w1 * vb + w2 * vc;
                       cv.put(x, y, cm.constant ? cm.at(0.5) : cm.at(cm.t(v)));
                     });
        }
    }
    // field lines
    auto lines = [&](const std::vector<float>& L, const LineStyle& st) {
      for (int mir : {1, -1})
        for (size_t i = 0; i + 3 < L.size(); i += 4)
          seg(clip, {X(mir * L[i]), Y(L[i + 1])}, {X(mir * L[i + 2]), Y(L[i + 3])}, 1.0 * u);
      flush(st.col, st.alpha);
    };
    if (draw_static) lines(sc.lines_static, ls_static);
    if (draw_pickup) lines(sc.lines_pickup, ls_pickup);
    // region outlines: dark casing, then the material colour
    std::vector<std::vector<P2>> loops_px;
    std::vector<C3> loop_col;
    for (const Region& g : sc.regions)
      for (const auto& L : g.loops)
        for (int mir : {1, -1}) {
          std::vector<P2> p;
          p.reserve(L.size());
          for (const P2& v : L) p.push_back({X(mir * v.x), Y(v.y)});
          loops_px.push_back(simplify(p, 0.15));
          loop_col.push_back(g.color);
        }
    for (const auto& p : loops_px) poly(clip, p, 2.6 * u);
    flush(th.outline, 0.92f);
    for (size_t i = 0; i < loops_px.size(); ++i) {
      poly(clip, loops_px[i], 1.0 * u);
      flush(mix(loop_col[i], {1, 1, 1}, 0.25f), 1.f);
    }
    // zero-thickness curves: superconducting sheets, thin magnetic layers
    for (const auto& c : sc.curves)
      for (int mir : {1, -1})
        for (size_t i = 0; i + 3 < c.size(); i += 4) seg(clip, {X(mir * c[i]), Y(c[i + 1])}, {X(mir * c[i + 2]), Y(c[i + 3])}, 3.2 * u);
    flush(th.outline, 0.92f);
    for (const std::string role : {"superconductor", "iron"}) {  // sheets, then thin magnetic layers
      for (size_t k = 0; k < sc.curves.size(); ++k) {
        const auto& c = sc.curves[k];
        const std::string ck = k < sc.curve_roles.size() ? sc.curve_roles[k] : "superconductor";
        if (ck != role) continue;
        for (int mir : {1, -1})
          for (size_t i = 0; i + 3 < c.size(); i += 4) seg(clip, {X(mir * c[i]), Y(c[i + 1])}, {X(mir * c[i + 2]), Y(c[i + 3])}, 1.4 * u);
      }
      flush(role_color(role), 1.f);
    }
    // symmetry axis (dash-dot), with a light halo
    {
      const std::vector<P2> ax{{X(0), plot.y0}, {X(0), plot.y1}};
      const auto pieces = dash_pieces(ax, {14 * u, 4 * u, 2.5 * u, 4 * u});
      for (auto& pc : pieces) seg(clip, pc.first, pc.second, 3.2 * u);
      flush(th.dark ? C3{0, 0, 0} : C3{1, 1, 1}, 0.55f);
      for (auto& pc : pieces) seg(clip, pc.first, pc.second, 1.3 * u);
      flush(th.dark ? C3{0.95f, 0.95f, 0.95f} : C3{0.05f, 0.05f, 0.06f}, 0.95f);
    }
    // frame, ticks and labels
    const double lw = std::max(1.0, std::round(u)), tl = std::round(6 * u);
    cv.frame({plot.x0 - lw, plot.y0 - lw, plot.x1 + lw, plot.y1 + lw}, lw, th.fg);
    for (double x : xt) {
      const double px = std::floor(X(x)) + 0.5;
      cv.rect(px - 0.5 * lw, plot.y1 - tl, px + 0.5 * lw, plot.y1, th.fg);
      cv.rect(px - 0.5 * lw, plot.y0, px + 0.5 * lw, plot.y0 + tl, th.fg);
      text_at(cv, px, plot.y1 + lw + gap_t, tick_label(x, step), s, th.fg, 0.5, 0);
    }
    for (double z : zt) {
      const double py = std::floor(Y(z)) + 0.5;
      cv.rect(plot.x0, py - 0.5 * lw, plot.x0 + tl, py + 0.5 * lw, th.fg);
      cv.rect(plot.x1 - tl, py - 0.5 * lw, plot.x1, py + 0.5 * lw, th.fg);
      text_at(cv, plot.x0 - lw - gap_t, py, tick_label(z, step), s, th.fg, 1, 0.5);
    }
    const std::string xl = "x (m)   [x = ±r, cut through the axis]";
    text_at(cv, 0.5 * (plot.x0 + plot.x1), plot.y1 + lw + gap_t + 7 * s + std::round(10 * u), xl, s, th.fg, 0.5, 0);
    const std::string zl = "z (m)";
    draw_text(cv, plot.x0 - lw - gap_t - zlab_w - std::round(10 * u) - 9 * s, 0.5 * (plot.y0 + plot.y1) + 0.5 * text_width(zl, s),
              zl, s, th.fg, false, true);

    // colour bar and panel
    if (!q.empty()) draw_cbar(F.cl, plot.x1 + cbar_gap, plot.y0, plot.y1);
    if (o.annotate) draw_panel(F.rows, F.pg, F.panel_x, top, H - m - top);
    draw_titles("section", {"meridional section, mirrored about the axis", extent_text()}, {0});
  }

