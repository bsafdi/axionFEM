struct Font {
  std::map<uint32_t, std::array<uint8_t, 9>> g;
  Font() {
    for (const GlyphSrc& s : kFont) {
      std::array<uint8_t, 9> rows{};
      int r = 0, c = 0;
      unsigned bits = 0;
      for (const char* p = s.rows; *p && r < 9; ++p) {
        if (*p != '.' && *p != '#') continue;
        bits = (bits << 1) | (*p == '#' ? 1u : 0u);
        if (++c == 5) {
          rows[r++] = static_cast<uint8_t>(bits);
          bits = 0;
          c = 0;
        }
      }
      g[s.cp] = rows;
    }
  }
  const std::array<uint8_t, 9>& get(uint32_t cp) const {
    auto it = g.find(cp);
    if (it == g.end()) it = g.find('?');
    return it->second;
  }
};
const Font& font() {
  static const Font f;
  return f;
}

uint32_t next_cp(const std::string& s, size_t& i) {
  const unsigned char c = static_cast<unsigned char>(s[i++]);
  if (c < 0x80) return c;
  int n = (c >= 0xF0) ? 3 : (c >= 0xE0) ? 2 : (c >= 0xC0) ? 1 : 0;
  uint32_t cp = c & (0x3Fu >> n);
  for (int k = 0; k < n && i < s.size(); ++k) cp = (cp << 6) | (static_cast<unsigned char>(s[i++]) & 0x3Fu);
  return cp;
}

int sub_scale(int s) { return std::max(1, (2 * s) / 3); }

struct GRun {
  uint32_t cp;
  int scale;
  double dx, dy;  // offset of the glyph cell's top-left from the text origin (output px)
};
struct TextLayout {
  std::vector<GRun> g;
  double width = 0;
};

// Markup: "_{..}" subscript, "^{..}" superscript; Unicode super/subscript
// digits and signs are mapped to the same.
TextLayout layout_text(const std::string& s, int scale) {
  TextLayout L;
  double x = 0;
  int mode = 0, last = scale;  // 0 normal, 1 superscript, 2 subscript
  auto emit = [&](uint32_t cp, int m) {
    const int sc = m ? sub_scale(scale) : scale;
    const double dy = m == 1 ? -1.0 * sc : m == 2 ? 7.0 * scale - 5.0 * sc : 0.0;
    L.g.push_back({cp, sc, x, dy});
    x += 6.0 * sc;
    last = sc;
  };
  size_t i = 0;
  while (i < s.size()) {
    const uint32_t cp = next_cp(s, i);
    if (mode == 0 && (cp == '_' || cp == '^') && i < s.size() && s[i] == '{') {
      mode = cp == '^' ? 1 : 2;
      ++i;
      continue;
    }
    if (mode && cp == '}') {
      mode = 0;
      continue;
    }
    if (cp == 0x2070) { emit('0', 1); continue; }
    if (cp == 0x00B9) { emit('1', 1); continue; }
    if (cp == 0x00B2) { emit('2', 1); continue; }
    if (cp == 0x00B3) { emit('3', 1); continue; }
    if (cp >= 0x2074 && cp <= 0x2079) { emit('4' + (cp - 0x2074), 1); continue; }
    if (cp == 0x207A) { emit('+', 1); continue; }
    if (cp == 0x207B) { emit(0x2212, 1); continue; }
    if (cp >= 0x2080 && cp <= 0x2089) { emit('0' + (cp - 0x2080), 2); continue; }
    emit(cp, mode);
  }
  L.width = L.g.empty() ? 0 : x - last;
  return L;
}

double text_width(const std::string& s, int scale) { return layout_text(s, scale).width; }

// Draw text with its top-left at (x, y) (output px).  `vertical` rotates the
// text 90 degrees counter-clockwise about (x, y): it then reads upwards and
// occupies [x, x + 9 scale) x (y - width, y].
void draw_text(Canvas& cv, double x, double y, const std::string& s, int scale, C3 col, bool bold = false,
               bool vertical = false) {
  const TextLayout L = layout_text(s, scale);
  x = std::round(x);
  y = std::round(y);
  // glyph-local (lx, ly) in output px -> canvas pixels
  auto map = [&](double lx, double ly) {
    return vertical ? P2{(x + ly) * cv.ss, (y - lx) * cv.ss} : P2{(x + lx) * cv.ss, (y + ly) * cv.ss};
  };
  const IBox all = cv.full();
  for (const GRun& g : L.g) {
    const auto& rows = font().get(g.cp);
    auto ink = [&](int c, int r) { return c >= 0 && c < 5 && r >= 0 && r < 9 && ((rows[r] >> (4 - c)) & 1); };
    const double bw = bold ? std::max(1, g.scale / 2) : 0;
    const double k = g.scale;
    for (int r = 0; r < 9; ++r) {
      if (!rows[r]) continue;
      for (int c = 0; c < 5; ++c) {
        if (!ink(c, r)) continue;
        const double lx = g.dx + c * k, ly = g.dy + r * k;
        const double w = k + bw, h = k;
        if (!vertical) cv.rect(x + lx, y + ly, x + lx + w, y + ly + h, col);
        else cv.rect(x + ly, y - lx - w, x + ly + h, y - lx, col);
      }
    }
    // Diagonal smoothing (scale >= 3): an empty cell whose two orthogonal
    // neighbours towards a corner are ink while the cell diagonally between
    // them is not gets the half of it on that corner's side, so diagonal
    // strokes and round letters read as continuous lines.
    if (g.scale < 3) continue;  // at small scales it makes strokes look heavy
    for (int r = -1; r <= 9; ++r)
      for (int c = -1; c <= 5; ++c) {
        if (ink(c, r)) continue;
        for (int dx : {-1, 1})
          for (int dy : {-1, 1}) {
            if (!(ink(c + dx, r) && ink(c, r + dy) && !ink(c + dx, r + dy))) continue;
            const double x0 = g.dx + c * k, y0 = g.dy + r * k, x1 = x0 + k, y1 = y0 + k;
            const double cxs = dx < 0 ? x0 : x1, cys = dy < 0 ? y0 : y1;  // the corner
            const P2 a = map(cxs, cys), b = map(dx < 0 ? x1 : x0, cys), cc = map(cxs, dy < 0 ? y1 : y0);
            raster_tri(all, a.x, a.y, b.x, b.y, cc.x, cc.y,
                       [&](int px, int py, double, double, double) { cv.put(px, py, col); });
          }
      }
  }
}

// Anchor helpers: ha/va in {0, 0.5, 1}; va refers to the cap height (7 rows).
void text_at(Canvas& cv, double x, double y, const std::string& s, int scale, C3 col, double ha, double va,
             bool bold = false) {
  const double w = text_width(s, scale);
  draw_text(cv, x - ha * w, y - va * 7.0 * scale, s, scale, col, bold);
}

// ============================================================ numbers
std::string minus_sign(double v) { return v < 0 ? "−" : ""; }

// Significant-digit formatting; very small/large values as m×10^{e}.
std::string fmt_g(double v, int sig = 3) {
  if (!std::isfinite(v)) return "n/a";
  if (v == 0) return "0";
  const double a = std::fabs(v);
  int e = static_cast<int>(std::floor(std::log10(a)));
  const double p = std::pow(10.0, sig - 1 - e);
  const double r = std::round(a * p) / p;
  e = static_cast<int>(std::floor(std::log10(r)));
  char buf[64];
  if (e >= -2 && e <= 3) {
    std::snprintf(buf, sizeof buf, "%.*f", std::max(0, sig - 1 - e), r);
    return minus_sign(v) + buf;
  }
  std::snprintf(buf, sizeof buf, "%.*f", sig - 1, r / std::pow(10.0, e));
  return minus_sign(v) + buf + "×10^{" + minus_sign(e) + std::to_string(std::abs(e)) + "}";
}

// Engineering prefix for SI units (H, J).
std::string fmt_si(double v, const std::string& unit, int sig = 3) {
  if (!std::isfinite(v)) return "n/a";
  if (v == 0) return "0 " + unit;
  int e3 = static_cast<int>(std::floor(std::floor(std::log10(std::fabs(v))) / 3.0)) * 3;
  e3 = std::min(12, std::max(-15, e3));
  static const std::map<int, std::string> pre = {{-15, "f"}, {-12, "p"}, {-9, "n"}, {-6, "μ"}, {-3, "m"},
                                                 {0, ""},    {3, "k"},   {6, "M"},  {9, "G"},       {12, "T"}};
  const double m = v / std::pow(10.0, e3);
  const int e = static_cast<int>(std::floor(std::log10(std::fabs(m))));
  char buf[64];
  std::snprintf(buf, sizeof buf, "%.*f", std::max(0, sig - 1 - e), std::fabs(m));
  return minus_sign(v) + buf + " " + pre.at(e3) + unit;
}

std::vector<double> nice_ticks(double lo, double hi, int target, double& step) {
  std::vector<double> t;
  const double span = hi - lo;
  if (!(span > 0) || !std::isfinite(span)) {
    step = 1;
    return t;
  }
  const double raw = span / std::max(1, target);
  const double mag = std::pow(10.0, std::floor(std::log10(raw)));
  const double r = raw / mag;
  step = (r < 1.5 ? 1 : r < 3 ? 2 : r < 7 ? 5 : 10) * mag;
  const long k0 = static_cast<long>(std::ceil(lo / step - 1e-9)), k1 = static_cast<long>(std::floor(hi / step + 1e-9));
  for (long k = k0; k <= k1; ++k) t.push_back(k * step);
  return t;
}

std::string tick_label(double v, double step) {
  const int dec = std::max(0, -static_cast<int>(std::floor(std::log10(step) + 1e-9)));
  char buf[64];
  std::snprintf(buf, sizeof buf, "%.*f", dec, std::fabs(v));
  const bool zero = std::fabs(v) < 0.5 * step;
  return (zero ? std::string() : minus_sign(v)) + buf;
}

