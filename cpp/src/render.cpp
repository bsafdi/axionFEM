// ============================================================ canvas
struct IBox {
  int x0 = 0, y0 = 0, x1 = 0, y1 = 0;  // [x0, x1) x [y0, y1) in canvas (supersampled) pixels
};
struct Box {
  double x0 = 0, y0 = 0, x1 = 0, y1 = 0;  // output pixels
  double w() const { return x1 - x0; }
  double h() const { return y1 - y0; }
};

struct Canvas {
  int W = 0, H = 0, ss = 1;
  std::vector<float> px;
  Canvas(int w, int h, int s, C3 bg) : W(w * s), H(h * s), ss(s), px(static_cast<size_t>(W) * H * 3) {
    for (size_t i = 0; i < px.size(); i += 3) {
      px[i] = bg.r;
      px[i + 1] = bg.g;
      px[i + 2] = bg.b;
    }
  }
  float* at(int x, int y) { return &px[3 * (static_cast<size_t>(y) * W + x)]; }
  void put(int x, int y, C3 c) {
    float* p = at(x, y);
    p[0] = c.r;
    p[1] = c.g;
    p[2] = c.b;
  }
  void blend(int x, int y, C3 c, float a) {
    float* p = at(x, y);
    p[0] += (c.r - p[0]) * a;
    p[1] += (c.g - p[1]) * a;
    p[2] += (c.b - p[2]) * a;
  }
  IBox ibox(const Box& b) const {
    IBox r{static_cast<int>(std::floor(b.x0 * ss)), static_cast<int>(std::floor(b.y0 * ss)),
           static_cast<int>(std::ceil(b.x1 * ss)), static_cast<int>(std::ceil(b.y1 * ss))};
    r.x0 = std::max(0, r.x0);
    r.y0 = std::max(0, r.y0);
    r.x1 = std::min(W, r.x1);
    r.y1 = std::min(H, r.y1);
    return r;
  }
  IBox full() const { return {0, 0, W, H}; }
  // Axis-aligned rectangle in output pixels with exact area coverage.
  void rect(double x0, double y0, double x1, double y1, C3 c, float a = 1.f) {
    x0 *= ss, y0 *= ss, x1 *= ss, y1 *= ss;
    const int ix0 = std::max(0, static_cast<int>(std::floor(x0))), ix1 = std::min(W, static_cast<int>(std::ceil(x1)));
    const int iy0 = std::max(0, static_cast<int>(std::floor(y0))), iy1 = std::min(H, static_cast<int>(std::ceil(y1)));
    for (int y = iy0; y < iy1; ++y) {
      const double cy = std::min<double>(y1, y + 1) - std::max<double>(y0, y);
      if (cy <= 0) continue;
      for (int x = ix0; x < ix1; ++x) {
        const double cx = std::min<double>(x1, x + 1) - std::max<double>(x0, x);
        if (cx <= 0) continue;
        const float cov = static_cast<float>(cx * cy) * a;
        if (cov >= 0.999f) put(x, y, c);
        else blend(x, y, c, cov);
      }
    }
  }
  void frame(const Box& b, double w, C3 c) {
    rect(b.x0, b.y0, b.x1, b.y0 + w, c);
    rect(b.x0, b.y1 - w, b.x1, b.y1, c);
    rect(b.x0, b.y0, b.x0 + w, b.y1, c);
    rect(b.x1 - w, b.y0, b.x1, b.y1, c);
  }
};

// Max-coverage mask for one stroke group.
struct Mask {
  int W, H;
  std::vector<float> m;
  int bx0, by0, bx1, by1;  // dirty box, inclusive
  Mask(int w, int h) : W(w), H(h), m(static_cast<size_t>(w) * h, 0.f) { reset(); }
  void reset() { bx0 = W, by0 = H, bx1 = -1, by1 = -1; }
  void grow(int x0, int y0, int x1, int y1) {
    bx0 = std::min(bx0, x0), by0 = std::min(by0, y0), bx1 = std::max(bx1, x1), by1 = std::max(by1, y1);
  }
  void cover(int x, int y, float c) {
    float& v = m[static_cast<size_t>(y) * W + x];
    if (c > v) v = c;
  }
  void composite(Canvas& cv, C3 col, float alpha) {
    for (int y = by0; y <= by1; ++y)
      for (int x = bx0; x <= bx1; ++x) {
        float& v = m[static_cast<size_t>(y) * W + x];
        if (v > 0.f) {
          cv.blend(x, y, col, alpha * std::min(1.f, v));
          v = 0.f;
        }
      }
    reset();
  }
};

struct AlwaysVisible {
  bool operator()(int, int, double) const { return true; }
};

// Round-capped segment a-b (canvas pixels) of half width hw, into the mask.
// `test(x, y, t)` may reject a pixel (depth test); t is the parameter of the
// closest point on the segment.
template <class Test>
void stroke_seg(Mask& M, const IBox& clip, double ax, double ay, double bx, double by, double hw, const Test& test) {
  if (!(std::isfinite(ax) && std::isfinite(ay) && std::isfinite(bx) && std::isfinite(by))) return;
  const double r = hw + 1.0;
  const int x0 = std::max(clip.x0, static_cast<int>(std::floor(std::min(ax, bx) - r)));
  const int x1 = std::min(clip.x1 - 1, static_cast<int>(std::ceil(std::max(ax, bx) + r)));
  const int y0 = std::max(clip.y0, static_cast<int>(std::floor(std::min(ay, by) - r)));
  const int y1 = std::min(clip.y1 - 1, static_cast<int>(std::ceil(std::max(ay, by) + r)));
  if (x0 > x1 || y0 > y1) return;
  const double dx = bx - ax, dy = by - ay, L2 = dx * dx + dy * dy;
  bool any = false;
  for (int y = y0; y <= y1; ++y) {
    const double py = y + 0.5;
    for (int x = x0; x <= x1; ++x) {
      const double px = x + 0.5;
      double t = L2 > 0 ? ((px - ax) * dx + (py - ay) * dy) / L2 : 0.0;
      t = std::min(1.0, std::max(0.0, t));
      const double qx = ax + t * dx - px, qy = ay + t * dy - py;
      const double c = hw + 0.5 - std::sqrt(qx * qx + qy * qy);
      if (c <= 0) continue;
      if (!test(x, y, t)) continue;
      M.cover(x, y, static_cast<float>(std::min(1.0, c)));
      any = true;
    }
  }
  if (any) M.grow(x0, y0, x1, y1);
}

// Split a polyline into "on" pieces of a dash pattern (lengths in output px).
std::vector<std::pair<P2, P2>> dash_pieces(const std::vector<P2>& p, const std::vector<double>& pattern) {
  std::vector<std::pair<P2, P2>> out;
  if (p.size() < 2 || pattern.empty()) return out;
  size_t k = 0;
  double left = pattern[0];
  for (size_t i = 0; i + 1 < p.size(); ++i) {
    P2 a = p[i];
    const P2 b = p[i + 1];
    double len = std::hypot(b.x - a.x, b.y - a.y);
    while (len > 1e-12) {
      const double step = std::min(len, left);
      const double t = step / len;
      const P2 m{a.x + (b.x - a.x) * t, a.y + (b.y - a.y) * t};
      if (k % 2 == 0) out.push_back({a, m});
      a = m;
      len -= step;
      left -= step;
      if (left <= 1e-12) {
        k = (k + 1) % pattern.size();
        left = pattern[k];
      }
    }
  }
  return out;
}

// Douglas-Peucker simplification (iterative).  Removes consecutive duplicates.
double seg_dist(const P2& p, const P2& a, const P2& b) {
  const double dx = b.x - a.x, dy = b.y - a.y, L2 = dx * dx + dy * dy;
  double t = L2 > 0 ? ((p.x - a.x) * dx + (p.y - a.y) * dy) / L2 : 0.0;
  t = std::min(1.0, std::max(0.0, t));
  return std::hypot(a.x + t * dx - p.x, a.y + t * dy - p.y);
}

std::vector<P2> simplify(const std::vector<P2>& in, double tol) {
  std::vector<P2> p;
  p.reserve(in.size());
  for (const P2& q : in) {
    if (!(std::isfinite(q.x) && std::isfinite(q.y))) continue;
    if (!p.empty() && std::fabs(q.x - p.back().x) + std::fabs(q.y - p.back().y) <= 1e-12 * (1 + std::fabs(q.x) + std::fabs(q.y)))
      continue;
    p.push_back(q);
  }
  if (p.size() < 3) return p;
  std::vector<char> keep(p.size(), 0);
  keep.front() = keep.back() = 1;
  std::vector<std::pair<size_t, size_t>> st{{0, p.size() - 1}};
  while (!st.empty()) {
    auto [i, j] = st.back();
    st.pop_back();
    if (j <= i + 1) continue;
    double dmax = -1;
    size_t kmax = i;
    for (size_t k = i + 1; k < j; ++k) {
      const double d = seg_dist(p[k], p[i], p[j]);
      if (d > dmax) dmax = d, kmax = k;
    }
    if (dmax > tol) {
      keep[kmax] = 1;
      st.push_back({i, kmax});
      st.push_back({kmax, j});
    }
  }
  std::vector<P2> out;
  for (size_t k = 0; k < p.size(); ++k)
    if (keep[k]) out.push_back(p[k]);
  return out;
}

// Triangle rasterizer: calls frag(x, y, w0, w1, w2) for canvas pixels whose
// centres lie inside (barycentric weights of a, b, c).  Either orientation.
template <class F>
void raster_tri(const IBox& clip, double ax, double ay, double bx, double by, double cx, double cy, const F& frag) {
  const double area = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
  if (!(std::fabs(area) > 1e-12)) return;  // degenerate or NaN
  const int x0 = std::max(clip.x0, static_cast<int>(std::floor(std::min({ax, bx, cx}))));
  const int x1 = std::min(clip.x1 - 1, static_cast<int>(std::ceil(std::max({ax, bx, cx}))));
  const int y0 = std::max(clip.y0, static_cast<int>(std::floor(std::min({ay, by, cy}))));
  const int y1 = std::min(clip.y1 - 1, static_cast<int>(std::ceil(std::max({ay, by, cy}))));
  if (x0 > x1 || y0 > y1) return;
  const double inv = 1.0 / area;
  constexpr double eps = -1e-9;
  for (int y = y0; y <= y1; ++y) {
    const double py = y + 0.5;
    for (int x = x0; x <= x1; ++x) {
      const double px = x + 0.5;
      const double w0 = ((bx - px) * (cy - py) - (by - py) * (cx - px)) * inv;
      if (w0 < eps) continue;
      const double w1 = ((cx - px) * (ay - py) - (cy - py) * (ax - px)) * inv;
      if (w1 < eps) continue;
      const double w2 = 1.0 - w0 - w1;
      if (w2 < eps) continue;
      frag(x, y, w0, w1, w2);
    }
  }
}

