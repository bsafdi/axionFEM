Image render_image(const nlohmann::json& scene, const RenderOptions& o) {
  validate(o);
  Renderer r(scene, o);
  if (r.sc.dim3) r.view3d_mesh(scene);
  else if (o.view == "3d") r.view3d(scene);
  else r.section(scene);
  return r.finish();
}

std::vector<unsigned char> encode_png(const Image& img) {
  AXF_REQUIRE(img.width > 0 && img.height > 0 &&
                  img.rgb.size() == static_cast<size_t>(img.width) * img.height * 3,
              "image buffer does not match its size", "", "pass an Image from render_image");
  std::vector<unsigned char> out;
  stbi_write_png_compression_level = 6;
  const int ok = stbi_write_png_to_func(png_sink, &out, img.width, img.height, 3, img.rgb.data(), img.width * 3);
  AXF_REQUIRE(ok != 0 && !out.empty(), "PNG encoding failed");
  return out;
}

std::vector<unsigned char> render_png(const nlohmann::json& scene, const RenderOptions& o) {
  return encode_png(render_image(scene, o));
}

void write_file(const std::string& path, const std::vector<unsigned char>& bytes) {
  std::ofstream f(path, std::ios::binary);
  AXF_REQUIRE(f.good(), "cannot open '" + path + "' for writing", "", "check that the directory exists and is writable");
  f.write(reinterpret_cast<const char*>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
  AXF_REQUIRE(f.good(), "failed writing '" + path + "'");
}

void write_png(const std::string& path, const nlohmann::json& scene, const RenderOptions& o) {
  write_file(path, render_png(scene, o));
}

RenderOptions options_from_json(const nlohmann::json& j) {
  RenderOptions o;
  if (j.is_null()) return o;
  AXF_REQUIRE(j.is_object(), "render options must be a JSON object", "/render");
  for (auto it = j.begin(); it != j.end(); ++it) {
    const std::string& k = it.key();
    const json& v = it.value();
    const std::string w = "/render/" + k;
    auto need = [&](bool ok, const char* type) {
      AXF_REQUIRE(ok, "render option '" + k + "' must be " + type, w);
    };
    if (k == "view") need(v.is_string(), "a string"), o.view = v.get<std::string>();
    else if (k == "quantity") need(v.is_string(), "a string"), o.quantity = v.get<std::string>();
    else if (k == "theme") need(v.is_string(), "a string"), o.theme = v.get<std::string>();
    else if (k == "title") need(v.is_string(), "a string"), o.title = v.get<std::string>();
    else if (k == "log_scale") need(v.is_boolean(), "true or false"), o.log_scale = v.get<bool>();
    else if (k == "field_lines") need(v.is_boolean(), "true or false"), o.field_lines = v.get<bool>();
    else if (k == "annotate") need(v.is_boolean(), "true or false"), o.annotate = v.get<bool>();
    else if (k == "width") need(v.is_number_integer(), "an integer"), o.width = v.get<int>();
    else if (k == "height") need(v.is_number_integer(), "an integer"), o.height = v.get<int>();
    else if (k == "supersample") need(v.is_number_integer(), "an integer"), o.supersample = v.get<int>();
    else if (k == "cutaway_deg") need(v.is_number(), "a number"), o.cutaway_deg = v.get<double>();
    else if (k == "elev_deg") need(v.is_number(), "a number"), o.elev_deg = v.get<double>();
    else if (k == "azim_deg") need(v.is_number(), "a number"), o.azim_deg = v.get<double>();
    else if (k == "vmin") need(v.is_number() || v.is_null(), "a number or null"), o.vmin = v.is_null() ? NAN : v.get<double>();
    else if (k == "vmax") need(v.is_number() || v.is_null(), "a number or null"), o.vmax = v.is_null() ? NAN : v.get<double>();
    else
      throw Error("unknown render option '" + k + "'", w,
                  "valid options: view, quantity, log_scale, width, height, field_lines, annotate, cutaway_deg, "
                  "elev_deg, azim_deg, theme, vmin, vmax, supersample, title");
  }
  validate(o);
  return o;
}

nlohmann::json options_to_json(const RenderOptions& o) {
  json j = {{"view", o.view},
            {"quantity", o.quantity},
            {"log_scale", o.log_scale},
            {"width", o.width},
            {"height", o.height},
            {"field_lines", o.field_lines},
            {"annotate", o.annotate},
            {"cutaway_deg", o.cutaway_deg},
            {"elev_deg", o.elev_deg},
            {"azim_deg", o.azim_deg},
            {"theme", o.theme},
            {"supersample", o.supersample},
            {"title", o.title}};
  j["vmin"] = std::isfinite(o.vmin) ? json(o.vmin) : json(nullptr);
  j["vmax"] = std::isfinite(o.vmax) ? json(o.vmax) : json(nullptr);
  return j;
}

