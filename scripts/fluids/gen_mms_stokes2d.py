"""Smoke-test MMS of the fluids Stokes C++ tests (cpp/tests/test_fluids_stokes.cpp): manufactured solution for planar
Stokes, both viscous forms, forcing derived with SymPy.

Writes cpp/tests/data/mms_stokes2d_generated.hpp (do not edit by hand; rerun this script).

  u = curl(psi) = (d_y psi, -d_x psi), psi = exp(x) (1 + y) sin(pi x) sin(pi y)
     psi = 0 on the boundary of the unit square, so u.n = 0 POINTWISE there: int u.n = 0 holds exactly for the
     P2 interpolant too, while the tangential velocity is nonzero (a real Dirichlet lift).
  p = cos(pi x) cos(pi y) + x y^2            (mean removed in the error computation)
  nu_const = 1                               (Laplacian form; variable nu needs the stress form)
  nu_var   = 1 + 0.5 sin(2 x + y)            (stress form)

  Laplacian form: f = -nu Lap u + grad p
  Stress form:    f = -div(2 nu eps(u)) + grad p
This is a smoke-test MMS, not the MMS of the verification cases (tools/fluids_mms generates those).
Run: python scripts/fluids/gen_mms_stokes2d.py
"""
import pathlib
import sympy as sp

x, y = sp.symbols("x y", real=True)
psi = sp.exp(x) * (1 + y) * sp.sin(sp.pi * x) * sp.sin(sp.pi * y)
u = sp.Matrix([sp.diff(psi, y), -sp.diff(psi, x)])
p = sp.cos(sp.pi * x) * sp.cos(sp.pi * y) + x * y**2
nu_c = sp.Integer(1)
nu_v = 1 + sp.Rational(1, 2) * sp.sin(2 * x + y)
X = [x, y]
assert sp.simplify(sp.diff(u[0], x) + sp.diff(u[1], y)) == 0

grad_u = sp.Matrix(2, 2, lambda i, j: sp.diff(u[i], X[j]))
grad_p = sp.Matrix([sp.diff(p, x), sp.diff(p, y)])
f_lap = sp.Matrix([-nu_c * (sp.diff(u[i], x, 2) + sp.diff(u[i], y, 2)) for i in range(2)]) + grad_p
eps = (grad_u + grad_u.T) / 2
f_str = sp.Matrix([-sum(sp.diff(2 * nu_v * eps[i, j], X[j]) for j in range(2)) for i in range(2)]) + grad_p
# boundary checks the docstring claims
for side in [(x, 0), (x, 1), (y, 0), (y, 1)]:
    n_comp = 0 if side[0] == x else 1
    assert sp.simplify(u[n_comp].subs(*side)) == 0, side

def cc(e):
    return sp.ccode(sp.simplify(e)) if len(str(e)) < 400 else sp.ccode(e)

out = ["// GENERATED by scripts/fluids/gen_mms_stokes2d.py (SymPy " + sp.__version__ + "). Do not edit.",
       "#pragma once", "#include <cmath>", "namespace axf::fluids::mms2d {",
       "inline void velocity(double x, double y, double* u) {",
       f"  u[0] = {cc(u[0])};", f"  u[1] = {cc(u[1])};", "}",
       "// row-major grad: g[2*i+j] = d u_i / d x_j",
       "inline void velocity_grad(double x, double y, double* g) {"]
for i in range(2):
    for j in range(2):
        out.append(f"  g[{2*i+j}] = {cc(grad_u[i, j])};")
out += ["}", f"inline double pressure(double x, double y) {{ return {cc(p)}; }}",
        f"inline double nu_variable(double x, double y) {{ return {cc(nu_v)}; }}",
        "inline void force_laplacian(double x, double y, double* f) {  // nu = 1",
        f"  f[0] = {cc(f_lap[0])};", f"  f[1] = {cc(f_lap[1])};", "}",
        "inline void force_stress(double x, double y, double* f) {  // nu = nu_variable",
        f"  f[0] = {cc(f_str[0])};", f"  f[1] = {cc(f_str[1])};", "}",
        "}  // namespace axf::fluids::mms2d", ""]
root = pathlib.Path(__file__).resolve().parents[2]
dst = root / "cpp/tests/data/mms_stokes2d_generated.hpp"
dst.write_text("\n".join(out).replace("M_PI", "M_PI"))
print("wrote", dst)
